export const I18N = { it, fr, de, en };
// The languages offered in the settings, in this order, each under its own name.
export const LANGS = [{ id: 'it', label: it.lang }, { id: 'fr', label: fr.lang }, { id: 'de', label: de.lang }, { id: 'en', label: en.lang }];

export function detectLang() {
  try {
    const saved = localStorage.getItem('learn.lang');
    if (saved && I18N[saved]) return saved;
  } catch { /* private mode */ }
  const nav = typeof navigator !== 'undefined' ? (navigator.language || 'fr').slice(0, 2).toLowerCase() : 'fr';
  return I18N[nav] ? nav : 'fr';
}
